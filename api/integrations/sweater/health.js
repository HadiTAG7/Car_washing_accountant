// جاهزية تكامل سويتر — «مضبوط أو لا»، بلا قيمةٍ أبداً
// ═══════════════════════════════════════════════════════════════════════════
// المشكلة التي يحلّها: `SWEATER_KEY_ENCRYPTION_KEY` لا يلمسه أي مسارٍ مجهول
// (البحث عن المفتاح في Firestore يسبق فكّ التعمية)، فلا سبيل لمعرفة أنه
// مضبوط إلا بالضغط على «أنشئ مفتاحاً» وتلقّي خطأ خام. وإعدادٌ لا يُرى إلا
// بالفشل إعدادٌ يُكتشف في أسوأ لحظة.
//
// ── ما يُقال وما لا يُقال ──
// يُقال: هل المتغيّر **موجود**. ولا يُقال: قيمته، ولا طولها، ولا بصمتها، ولا
// عدد المفاتيح، ولا أي بيانات. `Boolean(...)` وأسماءُ المفقود فقط.
//
// ── ولماذا بلا هوية ──
// من يعرف المسار يعرف أصلاً من `401` أن الباب موجود. ومعرفةُ أن الإعداد ناقص
// **تمنع** المحاولة لا تعينها: مفتاحٌ لا يُنشأ لا يُنتحَل. وربطُه بالهوية
// كان سيجعل أول ما يُفحص هو آخر ما يُرى — إذ الصفحة نفسها تحتاجه لتشرح لماذا
// فشل الزر.
//
// GET وحده. لا يقرأ Firestore ولا يكتب حرفاً.
// ═══════════════════════════════════════════════════════════════════════════

/** المتغيّرات التي بدونها لا يعمل التكامل، ولكلٍّ سببٌ يُقرأ. */
const REQUIRED = [
  {
    name: 'FIREBASE_SERVICE_ACCOUNT',
    why: 'بدونه لا يصل الخادم إلى قاعدة البيانات أصلاً.',
  },
  {
    name: 'SWEATER_KEY_ENCRYPTION_KEY',
    why: 'به تُعمّى أسرار مفاتيح الوكيل ويُتحقّق من توقيعها. بدونه لا يُنشأ مفتاح.',
  },
];

export default function handler(req, res) {
  if (req.method !== 'GET') {
    res.setHeader('Allow', 'GET');
    return res.status(405).json({ error: { code: 'invalid-argument', message: 'GET فقط.' } });
  }

  // `Boolean` على النصّ المُشذَّب: متغيّرٌ مضبوط على فراغ ليس مضبوطاً.
  const checked = REQUIRED.map((v) => ({
    name: v.name,
    present: Boolean(String(process.env[v.name] ?? '').trim()),
    why: v.why,
  }));
  const missing = checked.filter((v) => !v.present).map((v) => v.name);

  // لا تخزين وسيط: إجابةٌ قديمة عن جاهزيةٍ تغيّرت أسوأ من لا إجابة.
  res.setHeader('Cache-Control', 'no-store');
  return res.status(200).json({
    result: {
      ready: missing.length === 0,
      missing,
      checks: checked,
      hint: missing.length
        ? `أضِف ${missing.join('، ')} في متغيّرات بيئة الإنتاج ثم أعِد النشر.`
        : 'التكامل جاهز — أنشئ مفتاحاً من صفحة «تكامل سويتر».',
    },
  });
}
